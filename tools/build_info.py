"""PlatformIO pre-build script.

1. Defines GIT_REV (short commit hash, "-dirty" if uncommitted changes) so the
   firmware can show which source release it was built from (/licenses page).
2. Generates licenses_gz.h: every third-party notice and full licence text,
   gzip-compressed, served from flash at /licenses.txt. Kept in program flash
   (not SPIFFS) so uploading a new spiffs.bin can never remove it.

The header is written to $BUILD_DIR/generated/ and is not committed.
"""
import gzip
import os
import subprocess

Import("env")  # noqa: F821  (provided by PlatformIO/SCons)

project_dir = env.subst("$PROJECT_DIR")  # noqa: F821
out_dir = os.path.join(env.subst("$BUILD_DIR"), "generated")  # noqa: F821
os.makedirs(out_dir, exist_ok=True)


def git(*args):
    try:
        return subprocess.check_output(["git", *args], cwd=project_dir,
                                       stderr=subprocess.DEVNULL).decode().strip()
    except Exception:
        return ""


rev = git("rev-parse", "--short", "HEAD") or "unknown"
if git("status", "--porcelain", "--untracked-files=no"):
    rev += "-dirty"


def read(rel):
    with open(os.path.join(project_dir, rel), encoding="utf-8") as f:
        return f.read().replace("\r\n", "\n").strip() + "\n"


# MIT body without its title/copyright lines, reused for each MIT component.
mit_body = read("LICENSE").split("\n", 3)[3].lstrip("\n")


def mit(copyright_line):
    return "MIT License\n\n" + copyright_line + "\n\n" + mit_body


rule = "=" * 78 + "\n"
parts = [
    "CAN Bridge Analyzer - open source software notices\n",
    "Source code: https://github.com/boydsta/Can-Bridge-Analyzer\n",
    "Firmware built from commit: " + rev + "\n\n",
    read("THIRD_PARTY_LICENSES.md"),
]
sections = [
    ("CAN Bridge Analyzer (MIT)", read("LICENSE")),
    ("spud-diy - src/spud.h, parts of src/main.cpp (MIT)", mit("Copyright (c) 2024 Ra Cleave")),
    ("ACAN2517FD (MIT)", read("lib/ACAN2517FD/LICENSE")),
    ("CustomOTA-ESP32 (MIT)", mit("Copyright (c) 2025 Boyd Benton")),
    ("AsyncTCP, ESPAsyncWebServer, MCP_CAN_lib - GNU LGPL v3.0", read("licenses/LGPL-3.0.txt")),
    ("GNU GPL v3.0 (incorporated by LGPL v3.0; also Nissan Leaf DBC files)", read("data/LICENSE-GPL-3.0.txt")),
    ("Arduino core for ESP32 - GNU LGPL v2.1", read("licenses/LGPL-2.1.txt")),
    ("ESP-IDF - Apache License 2.0", read("licenses/Apache-2.0.txt")),
]
for title, text in sections:
    parts += ["\n", rule, title + "\n", rule, "\n", text]

data = gzip.compress("".join(parts).encode("utf-8"), compresslevel=9, mtime=0)

with open(os.path.join(out_dir, "licenses_gz.h"), "w", encoding="ascii") as f:
    f.write("/* Generated by tools/build_info.py - do not edit. */\n#pragma once\n")
    f.write("#include <stdint.h>\n#include <stddef.h>\n")
    f.write("static const uint8_t LICENSES_TXT_GZ[] = {\n")
    for i in range(0, len(data), 20):
        f.write("  " + ",".join(str(b) for b in data[i:i + 20]) + ",\n")
    f.write("};\nstatic const size_t LICENSES_TXT_GZ_LEN = sizeof(LICENSES_TXT_GZ);\n")

env.Append(CPPPATH=[out_dir])  # noqa: F821
env.Append(CPPDEFINES=[("GIT_REV", env.StringifyMacro(rev))])  # noqa: F821
print("build_info: GIT_REV=%s, licenses_gz.h %d bytes" % (rev, len(data)))
